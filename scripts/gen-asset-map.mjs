// Generates src/data/asset-map.ts: maps './assets/<path>' -> data URI.
// Runs before `vite build` so the deployed site is text-only (GitHub MCP safe).
import fs from 'node:fs';
import path from 'node:path';

const ROOT = 'assets-src';
const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp', '.gif': 'image/gif', '.svg': 'image/svg+xml' };

const entries = [];
function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) { walk(full); continue; }
    const ext = path.extname(name).toLowerCase();
    if (!MIME[ext] || name === 'favicon-64.png') continue;
    const rel = './assets/' + path.relative(ROOT, full).split(path.sep).join('/');
    const b64 = fs.readFileSync(full).toString('base64');
    entries.push(`  ${JSON.stringify(rel)}: 'data:${MIME[ext]};base64,${b64}',`);
  }
}
walk(ROOT);
const out = '// AUTO-GENERATED by scripts/gen-asset-map.mjs — do not edit.\n' +
  'export const ASSET_MAP: Record<string, string> = {\n' + entries.join('\n') + '\n};\n';
fs.mkdirSync('src/data', { recursive: true });
fs.writeFileSync('src/data/asset-map.ts', out);
console.log('asset-map entries:', entries.length, 'size:', (out.length / 1024).toFixed(0) + 'KB');

// Ship the editable content as dist/content.json (via public/) so the Admin
// panel can update the live site through the GitHub API without a rebuild.
fs.mkdirSync('public', { recursive: true });
fs.copyFileSync('src/data/content.json', 'public/content.json');
console.log('public/content.json updated');
